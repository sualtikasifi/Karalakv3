// Lists every module app.js pulls in (static imports, depth-first) and writes <link rel="modulepreload"> tags into hosting/oyna/index.html,
// so the browser fetches the whole module graph in ONE parallel wave instead of one round trip per import level.
// Run after adding or removing a web module:  node scripts/gen_web_preload.js
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..", "hosting", "oyna"), seen = new Set();
(function walk(f) {
  if (seen.has(f)) return; seen.add(f);
  const src = fs.readFileSync(path.join(root, f), "utf8");
  for (const m of src.matchAll(/^\s*import\s[^"']*?["']\.\/([^"']+\.js)["']/gm)) walk(m[1]);
})("app.js");
const CDN = "https://www.gstatic.com/firebasejs/10.14.1", sdk = ["firebase-app.js", "firebase-auth.js", "firebase-firestore.js"].map((f) => `<link rel="modulepreload" href="${CDN}/${f}">`).join("\n");
const tags = `<link rel="preconnect" href="https://www.gstatic.com" crossorigin>\n${sdk}\n` + [...seen].map((f) => `<link rel="modulepreload" href="${f}">`).join("\n");
const file = path.join(root, "index.html"), html = fs.readFileSync(file, "utf8"), block = `<!-- preload:start (generated by scripts/gen_web_preload.js) -->\n${tags}\n<!-- preload:end -->`;
fs.writeFileSync(file, /<!-- preload:start[\s\S]*?<!-- preload:end -->/.test(html) ? html.replace(/<!-- preload:start[\s\S]*?<!-- preload:end -->/, block) : html.replace("</head>", block + "\n</head>"));
console.log(seen.size + " modules");
