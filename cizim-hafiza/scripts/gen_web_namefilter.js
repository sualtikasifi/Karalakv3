// The name filter's word lists (domain/model/NameFilter.kt) for the web game: writes hosting/oyna/namefilter_data.js, which
// hosting/oyna/namefilter.js reads, so a name refused in the app is refused in the browser too.
// Run after NameFilter.kt changes:  node scripts/gen_web_namefilter.js   (from the repo's cizim-hafiza folder). Commit the result.
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const kt = fs.readFileSync(path.join(root, "app/src/main/java/com/sualtikasifi/cizimhafiza/domain/model/NameFilter.kt"), "utf8");
const list = (name) => {
  const m = kt.match(new RegExp(`val ${name}: \\w+<String> = \\w+\\(([\\s\\S]*?)\\n    \\)`));
  if (!m) throw new Error(`${name} not found in NameFilter.kt`);
  return [...m[1].replace(/\/\/.*$/gm, "").matchAll(/"([^"]+)"/g)].map((x) => x[1]);
};
const out = `// Generated by scripts/gen_web_namefilter.js from NameFilter.kt — do not edit by hand.\nexport const SUBSTRINGS = ${JSON.stringify(list("SUBSTRINGS"))};\nexport const TOKENS = ${JSON.stringify(list("TOKENS"))};\n`;
fs.writeFileSync(path.join(root, "hosting/oyna/namefilter_data.js"), out);
console.log(`namefilter_data.js: ${list("SUBSTRINGS").length} substrings, ${list("TOKENS").length} tokens`);
